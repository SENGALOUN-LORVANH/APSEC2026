import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from leakage_guard import LeakageError, check_request, developer_fix_fingerprint, find_leaks  # noqa: E402

META = {"patch_id": "Patches_ICSE__Doverfitting__Kali__Math__patch1-Math-80-Kali-plausible",
        "APR_tool": "Kali", "original_dataset_location": "Patches.zip:Patches/Patches_ICSE/Doverfitting/Kali/Math/x"}
TOOLS = ["Kali", "jKali", "Arja", "TBar", "SimFix", "ACS"]
CLEAN = """--- /src/main/java/org/apache/commons/math/linear/EigenDecompositionImpl.java
+++ /src/main/java/org/apache/commons/math/linear/EigenDecompositionImpl.java
@@ -1,3 +1,3 @@
-    if (x > 0) {
+    if (x >= 0) {
"""


def test_clean_payload_passes(tmp_path):
    assert check_request(CLEAN, META, TOOLS, errors_path=tmp_path / "e.jsonl")


@pytest.mark.parametrize("snippet,reason", [
    ("label: correct", "label annotation"),
    ("This patch is OVERFITTING", "label annotation"),
    ("ground truth says", "label annotation"),
    ("patch1-Math-80-Kali-plausible", "dataset suffix"),
    ("see Doverfitting folder", "archive folder token"),
    ("generated by SimFix", "APR tool identifier"),
    ("/data/qc_workspaces/fixed_oracle/Math_80/src", "fixed-oracle path"),
])
def test_leaks_detected(snippet, reason):
    reasons = find_leaks(CLEAN + snippet, META, TOOLS)
    assert any(reason in r for r in reasons), reasons


def test_tool_name_word_boundary_no_false_positive():
    assert not find_leaks(CLEAN + "int kalimba = TBarrier + SimFixed;", META, ["TBar", "SimFix"])
    # Case-sensitive: lowercase English word is not a tool id.
    assert not find_leaks(CLEAN + "int acs_count = 1;", META, ["ACS"])


def test_abort_is_logged_and_raises(tmp_path):
    err = tmp_path / "errors.jsonl"
    with pytest.raises(LeakageError):
        check_request(CLEAN + "OVERFITTING", META, TOOLS, purpose="semantic", errors_path=err)
    entry = json.loads(err.read_text().splitlines()[0])
    assert entry["type"] == "LEAKAGE_ABORT" and entry["purpose"] == "semantic"


def test_developer_fix_canary_detected():
    buggy = "class A {\n  int f(int x) {\n    return x + 1;\n  }\n}\n"
    fixed = "class A {\n  int f(int x) {\n    return computeCanaryValue_7f3a(x);\n  }\n}\n"
    candidate_diff = "@@ -3 +3 @@\n-    return x + 1;\n+    return x + 2;\n"
    fp = developer_fix_fingerprint(buggy, fixed, candidate_diff)
    assert len(fp) == 1
    payload = CLEAN + "\n    return computeCanaryValue_7f3a(x);\n"
    assert any("developer-fix fingerprint" in r for r in find_leaks(payload, META, TOOLS, fp))
    assert not find_leaks(CLEAN, META, TOOLS, fp)


def test_candidate_identical_to_developer_fix_is_allowed():
    buggy = "class A {\n  int f(int x) {\n    return x + 1;\n  }\n}\n"
    fixed = "class A {\n  int f(int x) {\n    return Math.max(x, 0) + 1;\n  }\n}\n"
    candidate_diff = "@@ -3 +3 @@\n-    return x + 1;\n+    return Math.max(x, 0) + 1;\n"
    fp = developer_fix_fingerprint(buggy, fixed, candidate_diff)
    assert fp == set()
    assert not find_leaks(candidate_diff, META, TOOLS, fp)
